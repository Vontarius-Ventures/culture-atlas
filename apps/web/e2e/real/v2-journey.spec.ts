  await test.step('arm the phone and run a remote capture command lifecycle', async () => {
    const session = await phone.call('POST', '/v2/device/capture-sessions', {
      source: 'phone_camera',
      mode: 'photo',
      local_session_id: randomUUID(),
    });
    expect(session.status, JSON.stringify(session.body)).toBe(201);
    await phone.heartbeat();
    const armed = await phone.call(
      'POST',
      `/v2/device/capture-sessions/${session.body.session_id}/arm`,
      { enabled: true, duration_seconds: 600, allowed_agent_connection_ids: [connectionId] },
    );
    expect(armed.status, JSON.stringify(armed.body)).toBe(200);
    // The agent asks for a photo.
    const requested = await fetch(
      new URL(`/v2/devices/${phone.installationId}/commands`, baseURL),
      {
        method: 'POST',
        headers: {
          authorization: `Bearer ${credential}`,
          'content-type': 'application/json',
          'idempotency-key': randomUUID(),
        },
        body: JSON.stringify({
          session_id: session.body.session_id,
          generation: session.body.generation,
          action: 'capture_photo',
          capture_client_id: randomUUID(),
        }),
      },
    );
    const command = await requested.json();
    expect(requested.status, JSON.stringify(command)).toBeLessThan(300);
    // The phone claims it (bounded long poll) and acknowledges it in order.
    const claimed = await phone.call('GET', '/v2/device/commands?after_sequence=0&wait=5');
    expect(claimed.status, JSON.stringify(claimed.body)).toBe(200);
    const delivered = claimed.body.items.find(
      (i: { command_id: string }) => i.command_id === command.command_id,
    );
    expect(delivered, JSON.stringify(claimed.body)).toBeTruthy();
    for (const ack of [
      { sequence: 1, state: 'executing' },
      { sequence: 1, state: 'executing' }, // a retried ack is idempotent
      { sequence: 2, state: 'succeeded' },
    ]) {
      const res = await phone.call('POST', `/v2/device/commands/${command.command_id}/ack`, ack);
      expect(res.status, JSON.stringify(res.body)).toBe(200);
    }
    const final = await fetch(new URL(`/v2/commands/${command.command_id}`, baseURL), {
      headers: { authorization: `Bearer ${credential}` },
    });
    const finalBody = await final.json();
    expect(final.status, JSON.stringify(finalBody)).toBe(200);
    expect(finalBody.state).toBe('succeeded');
  });

