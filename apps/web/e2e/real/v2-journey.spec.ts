function mailTime(file: string): number {
  // Files are named `<ISO time with ':' replaced by '-'>-<uuid>.json`.
  const iso = file.slice(0, 19).replace(/T(\d\d)-(\d\d)-(\d\d)$/, 'T$1:$2:$3');
  return new Date(`${iso}Z`).getTime();
}

/** Newest identity mail for this address since `after` (the file mailbox is local-dev only). */
async function mailFor(email: string, after: number): Promise<{ callback: string }> {
  let found: { callback: string } | undefined;
  await expect
    .poll(
      () => {
        const files = readdirSync(MAIL_DIR)
          .filter((f) => f.endsWith('.json') && mailTime(f) >= after - 2000)
          .sort()
          .reverse();
        for (const file of files) {
          const mail = JSON.parse(readFileSync(path.join(MAIL_DIR, file), 'utf8'));
          if (mail.to === email) {
            found = mail;
            return true;
          }
        }
        return false;
      },
      { timeout: 20_000 },
    )
    .toBe(true);
  return found!;
}

/** Browser-session mutation headers, exactly as the web client sends them. */
async function mutationHeaders(request: APIRequestContext): Promise<Record<string, string>> {
  const session = await (await request.get('/v1/session')).json();
  return {
    'x-csrf-token': session.csrf_token,
    'x-atlas-expected-account': session.principal.account_id,
    'idempotency-key': randomUUID(),
    'content-type': 'application/json',
  };
}

/** A fake native client: the same HTTP rules the Swift and Kotlin API clients follow. */
class FakePhone {
  readonly installationPublicId = randomUUID();
  readonly key = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  accountId = '';
  installationId = '';
  access = '';
  sequence = 0;
  constructor(readonly base: string) {}

  jwk() {
    const { x, y } = this.key.publicKey.export({ format: 'jwk' });
    return { kty: 'EC', crv: 'P-256', x, y };
  }
  async call(
    method: string,
    route: string,
    body?: unknown,
    opts: { auth?: boolean; expected?: string } = {},
    // Untyped JSON from the wire, as a native client sees it; every use is asserted.
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
  ): Promise<{ status: number; body: any }> {
    const headers: Record<string, string> = {};
    if (opts.auth !== false) headers.authorization = `Bearer ${this.access}`;
    if (method !== 'GET') {
      headers['idempotency-key'] = randomUUID();
      headers['x-atlas-expected-account'] = opts.expected ?? this.accountId;
    }
    if (body !== undefined) headers['content-type'] = 'application/json';
    const res = await fetch(new URL(route, this.base), {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await res.text();
    return { status: res.status, body: text ? JSON.parse(text) : null };
  }
  async signIn(email: string) {
    const verifier = randomBytes(32).toString('base64url');
    const state = randomBytes(32).toString('base64url');
    const nonce = randomBytes(32).toString('base64url');
    const started = Date.now();
    const start = await this.call(
      'POST',
      '/v2/identity/email/start',
      {
        email,
        purpose: 'sign_in',
        destination: 'android',
        state,
        nonce,
        code_challenge: createHash('sha256').update(verifier).digest('base64url'),
      },
      { auth: false },
    );
    expect(start.status, JSON.stringify(start.body)).toBe(200);
    const mail = await mailFor(email, started);
    const callback = new URL(mail.callback);
    expect(`${callback.origin}${callback.pathname}`).toBe(
      'https://app.cultureatlas.com/identity/callback',
    );
    const fragment = new URLSearchParams(callback.hash.slice(1));
    expect(fragment.get('state')).toBe(state);
    const complete = await this.call(
      'POST',
      '/v2/identity/email/complete',
      {
        challenge_id: fragment.get('challenge_id'),
        token: fragment.get('token'),
        state,
        nonce,
        code_verifier: verifier,
      },
      { auth: false },
    );
    expect(complete.status, JSON.stringify(complete.body)).toBe(200);
    return complete.body as { account_id: string; enrollment_grant: string };
  }
  async enroll(grant: { account_id: string; enrollment_grant: string }) {
    const challenge = await this.call(
      'POST',
      '/v2/devices/enrollment/challenge',
      {
        enrollment_grant: grant.enrollment_grant,
        installation_public_id: this.installationPublicId,
        platform: 'android',
        public_key: this.jwk(),
      },
      { auth: false, expected: grant.account_id },
    );
    expect(challenge.status, JSON.stringify(challenge.body)).toBe(201);
    const nonce = challenge.body.nonce as string;
    const payload = [
      SIGNATURE_PREFIX,
      nonce,
      this.installationPublicId,
      'android',
      createHash('sha256').update(grant.enrollment_grant).digest('hex'),
    ].join('\n');
    const signature = sign('sha256', Buffer.from(payload), {
      key: this.key.privateKey,
      dsaEncoding: 'ieee-p1363',
    }).toString('base64url');
    const enrolled = await this.call(
      'POST',
      '/v2/devices/enroll',
      {
        platform: 'android',
        app_version: '1.0.0 (1)',
        installation_public_id: this.installationPublicId,
        enrollment_grant: grant.enrollment_grant,
        proof: { nonce, signature, public_key: this.jwk() },
        capabilities: { photo: true, video: true, meta_glasses_sdk: false },
      },
      { auth: false, expected: grant.account_id },
    );
    expect(enrolled.status, JSON.stringify(enrolled.body)).toBe(201);
    this.accountId = grant.account_id;
    this.installationId = enrolled.body.installation.id;
    this.access = enrolled.body.native_session.access_token;
    expect(this.access).toMatch(/^cna_/);
  }
  async heartbeat() {
    const res = await this.call('PUT', '/v2/device/status', {
      sequence: ++this.sequence,
      capabilities: { photo: true, video: true, microphone: false },
      readiness: 'ready',
      app_state: 'foreground',
    });
    expect(res.status, JSON.stringify(res.body)).toBe(200);
  }
}

